"""Deterministic seeding of the laboratory database.

Identifiers are fixed so that URLs and sessions survive a reseed or a
restart. Rows are inserted with the product's own services where a service
exists (destinations, table refresh, agent tokens); the remaining rows
(organizations, users with a laboratory password, sources, pipelines) are
inserted directly because the product has no equivalent non-interactive path.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone

from sqlalchemy import delete, insert, select, update
from sqlalchemy.engine import Engine

from quadringent.table_discovery import DiscoveredTable
from quadringent_control_plane.v2 import schema as v2_schema
from quadringent_control_plane.v2.crypto import SecretBox, hash_password
from quadringent_control_plane.v2.services.agent_tokens import AgentTokensService
from quadringent_control_plane.v2.services.destinations import DestinationsService
from quadringent_control_plane.v2.services.tables import TablesService

from . import LAB_OTHER_ORG_ID, LAB_ORG_ID, fixtures

_PASSWORD_HASH: str | None = None
# Destination rows are expensive to generate (RSA key pair); the first one per
# account is generated by the product service and reused with a fixed id.
_DESTINATION_ROWS: dict[str, dict[str, object]] = {}


@dataclass
class SeedResult:
    """Identifiers of what was seeded, plus values that must not be exposed."""

    org_ids: tuple[str, ...] = (LAB_ORG_ID, LAB_OTHER_ORG_ID)
    users: dict[str, str] = field(default_factory=dict)
    source_id: str = fixtures.SOURCE_ID
    destination_id: str = fixtures.DESTINATION_ID
    table_ids: dict[str, str] = field(default_factory=dict)
    pipeline_ids: dict[str, str] = field(default_factory=dict)
    other_source_id: str = fixtures.OTHER_SOURCE_ID
    other_destination_id: str = fixtures.OTHER_DESTINATION_ID
    other_table_id: str = "tbl_other_orders"
    other_pipeline_id: str = fixtures.PIPELINE_OTHER_ORDERS
    # Never returned by the lab router; kept for tests only.
    generated: dict[str, str] = field(default_factory=dict)

    def public(self) -> dict[str, object]:
        return {
            "orgs": list(self.org_ids),
            "users": dict(self.users),
            "source_id": self.source_id,
            "destination_id": self.destination_id,
            "table_ids": dict(self.table_ids),
            "pipeline_ids": dict(self.pipeline_ids),
            "other": {
                "source_id": self.other_source_id,
                "destination_id": self.other_destination_id,
                "table_id": self.other_table_id,
                "pipeline_id": self.other_pipeline_id,
            },
        }


class OtherOrgDiscovery:
    """Fixed one-table catalog for the other organization (not scenario driven)."""

    def discover(self, *, libraries, limit, search):  # noqa: ANN001 - protocol signature
        return (
            DiscoveredTable(
                library="OTHERLIB",
                system_name="ORDERS",
                sql_name="ORDERS",
                text=None,
                row_count=50,
                size_bytes=6400,
                has_key=True,
                key_columns=("ORDER_ID",),
                journaled=True,
                journal_library="OTHERLIB",
                journal_name="OTHERJRN",
                images="*BOTH",
                omitted=False,
            ),
        )


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _password_hash() -> str:
    global _PASSWORD_HASH
    if _PASSWORD_HASH is None:
        _PASSWORD_HASH = hash_password(fixtures.LAB_PASSWORD)
    return _PASSWORD_HASH


def reset_database(engine: Engine) -> None:
    """Delete every row, children first. The database is the lab's own file."""

    with engine.begin() as connection:
        for table in reversed(v2_schema.metadata.sorted_tables):
            connection.execute(delete(table))


def _insert_destination(engine: Engine, secret_box: SecretBox, org_id: str, destination_id: str, account: str) -> None:
    cached = _DESTINATION_ROWS.get(account)
    if cached is None:
        service = DestinationsService(engine, secret_box, org_id=org_id)
        record, _private_key = service.create(snowflake_account=account)
        with engine.begin() as connection:
            row = dict(
                connection.execute(select(v2_schema.destinations).where(v2_schema.destinations.c.id == record.id))
                .mappings()
                .one()
            )
            connection.execute(delete(v2_schema.destinations).where(v2_schema.destinations.c.id == record.id))
        _DESTINATION_ROWS[account] = row
        cached = row
    row = dict(cached)
    row.update({"id": destination_id, "org_id": org_id, "verification_state": "declared_not_verified", "paused_at": None})
    with engine.begin() as connection:
        connection.execute(insert(v2_schema.destinations), row)


def _rekey_tables(engine: Engine, source_id: str, prefix: str) -> dict[str, str]:
    """Give the refreshed tables fixed identifiers (no pipeline references them yet)."""

    ids: dict[str, str] = {}
    with engine.begin() as connection:
        rows = connection.execute(
            select(v2_schema.tables.c.id, v2_schema.tables.c.table_name).where(v2_schema.tables.c.source_id == source_id)
        ).all()
        for old_id, name in rows:
            new_id = f"{prefix}{name.lower()}"
            connection.execute(update(v2_schema.tables).where(v2_schema.tables.c.id == old_id).values(id=new_id))
            ids[name] = new_id
    return ids


def seed(engine: Engine, secret_box: SecretBox, discovery: object, *, canaries: bool = False) -> SeedResult:
    """Reset the database and insert the deterministic laboratory dataset."""

    reset_database(engine)
    moment = _now()
    result = SeedResult()

    with engine.begin() as connection:
        connection.execute(insert(v2_schema.organizations), {"id": LAB_ORG_ID, "name": "Laboratory organization"})
        connection.execute(
            insert(v2_schema.organizations), {"id": LAB_OTHER_ORG_ID, "name": "Laboratory other organization"}
        )
        for email, role, org_id in (
            (fixtures.OPERATOR_EMAIL, "admin", LAB_ORG_ID),
            (fixtures.READER_EMAIL, "reader", LAB_ORG_ID),
            (fixtures.OTHER_ADMIN_EMAIL, "admin", LAB_OTHER_ORG_ID),
        ):
            user_id = fixtures.USER_IDS[email]
            connection.execute(
                insert(v2_schema.users),
                {
                    "id": user_id,
                    "org_id": org_id,
                    "email": email,
                    "role": role,
                    "password_hash": _password_hash(),
                    "oidc_subject": None,
                    "created_at": moment,
                    "activated_at": moment,
                },
            )
            result.users[email] = user_id
        host = fixtures.CANARY_HOST if canaries else fixtures.SOURCE_HOST
        user = fixtures.CANARY_USER if canaries else fixtures.SOURCE_USER
        secret = fixtures.CANARY_SECRET if canaries else fixtures.SOURCE_SECRET
        for source_id, org_id, source_host, source_user, source_secret, name in (
            (fixtures.SOURCE_ID, LAB_ORG_ID, host, user, secret, "Laboratory IBM i (synthetic)"),
            (
                fixtures.OTHER_SOURCE_ID,
                LAB_OTHER_ORG_ID,
                "ibmi.lab-other.invalid",
                "OTHERUSER",
                "lab-fixture-other-secret",
                "Other organization IBM i (synthetic)",
            ),
        ):
            connection.execute(
                insert(v2_schema.sources),
                {
                    "id": source_id,
                    "org_id": org_id,
                    "display_name": name,
                    "ibmi_host": source_host,
                    "ibmi_user": source_user,
                    "secret_ciphertext": secret_box.encrypt(source_secret),
                    "created_at": moment,
                    "updated_at": moment,
                },
            )

    _insert_destination(
        engine, secret_box, LAB_ORG_ID, fixtures.DESTINATION_ID,
        fixtures.CANARY_ACCOUNT if canaries else fixtures.DESTINATION_ACCOUNT,
    )
    _insert_destination(
        engine, secret_box, LAB_OTHER_ORG_ID, fixtures.OTHER_DESTINATION_ID, "lab-fixture-other-account"
    )

    tables = TablesService(engine)
    tables.refresh(fixtures.SOURCE_ID, discovery_client=discovery)  # type: ignore[arg-type]
    result.table_ids = _rekey_tables(engine, fixtures.SOURCE_ID, "tbl_")
    tables.refresh(fixtures.OTHER_SOURCE_ID, discovery_client=OtherOrgDiscovery())
    other_ids = _rekey_tables(engine, fixtures.OTHER_SOURCE_ID, "tbl_other_")
    result.other_table_id = other_ids["ORDERS"]

    for pipeline_id, table_name, destination_id, declared_state in (
        (fixtures.PIPELINE_ORDERS, "ORDERS", fixtures.DESTINATION_ID, "live"),
        (fixtures.PIPELINE_CUSTOMERS, "CUSTOMERS", fixtures.DESTINATION_ID, "copying"),
    ):
        _insert_pipeline(engine, pipeline_id, result.table_ids[table_name], destination_id, declared_state, moment)
        result.pipeline_ids[table_name] = pipeline_id
    _insert_pipeline(
        engine, fixtures.PIPELINE_OTHER_ORDERS, result.other_table_id, fixtures.OTHER_DESTINATION_ID, "live", moment
    )

    if canaries:
        _, token = AgentTokensService(engine, org_id=LAB_ORG_ID, pepper=fixtures.TOKEN_PEPPER).create(
            name="laboratory read token", scope="read", created_by="lab", never_expires=True
        )
        result.generated["agent_token"] = token
    return result


def _insert_pipeline(
    engine: Engine, pipeline_id: str, table_id: str, destination_id: str, declared_state: str, moment: datetime
) -> None:
    with engine.begin() as connection:
        connection.execute(
            insert(v2_schema.pipelines),
            {
                "id": pipeline_id,
                "table_id": table_id,
                "destination_id": destination_id,
                "declared_state": declared_state,
                "created_at": moment,
                "updated_at": moment,
            },
        )

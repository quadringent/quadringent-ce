"""IBM i qualification DML and source oracle via the capture image's JVM.

Only SQL generated by the deterministic qualification scenario is accepted.
The source password is read from a private file and sent to the short-lived
Java process on stdin; it never enters Docker arguments or the environment.
This driver is for a dedicated synthetic table, never an application table.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
import json
import os
from pathlib import Path
import re
import queue
import threading
import stat
import subprocess
from typing import Any, Callable, Sequence
from uuid import UUID, uuid4

from .adapters import SourceResult
from .config import RunConfig
from .generator import DML_STEP_NAMES, LABEL, freshness_markers, step_plan
from .schema import update_sql


_IMAGE_DIGEST = re.compile(r"(?:\S+@)?sha256:[0-9a-f]{64}\Z")
_SOURCE_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,127}\Z")
_RECEIVER = re.compile(r"[A-Za-z0-9_$#@]{1,128}\Z")
_HOST = re.compile(r"[A-Za-z0-9][A-Za-z0-9.-]{0,252}\Z")
_USER = re.compile(r"[A-Za-z0-9_$#@]{1,128}\Z")
_KEYCHAIN_SERVICE = re.compile(r"[A-Za-z0-9][A-Za-z0-9/_-]{0,127}\Z")
_JAVA_CLASS = "io.quadringent.as400.QualificationSourceDriver"
_JAVA_CLASSPATH = "/app/probe.jar:/app/lib/*"


@dataclass(frozen=True)
class _Credential:
    host: str
    user: str
    password: str = field(repr=False)


def _load_credential(path_text: str, *, configured_host: str | None,
                     configured_user: str | None) -> _Credential:
    if path_text.startswith("keychain:"):
        service = path_text.removeprefix("keychain:")
        if _KEYCHAIN_SERVICE.fullmatch(service) is None:
            raise ValueError("source keychain service is invalid")
        if configured_host is None or configured_user is None:
            raise ValueError("source host and user are required with keychain")
        if _HOST.fullmatch(configured_host) is None or _USER.fullmatch(configured_user) is None:
            raise ValueError("source host or user is invalid")
        try:
            completed = subprocess.run(
                ["security", "find-generic-password", "-s", service, "-w"],
                capture_output=True, text=True, check=False, timeout=10,
            )
        except (OSError, subprocess.TimeoutExpired):
            raise ValueError("source keychain item is unavailable") from None
        password = completed.stdout.removesuffix("\n")
        if completed.returncode != 0 or not password or len(password) > 8192 or "\n" in password or "\r" in password:
            raise ValueError("source keychain item is unavailable")
        return _Credential(configured_host, configured_user, password)
    path = Path(path_text)
    try:
        if not hasattr(os, "O_NOFOLLOW"):
            raise ValueError("source secret requires a no-follow file open")
        descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
        with os.fdopen(descriptor, "r", encoding="utf-8") as handle:
            metadata = os.fstat(handle.fileno())
            if not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != os.getuid():
                raise ValueError("source secret must be an owned regular file")
            if stat.S_IMODE(metadata.st_mode) & 0o077:
                raise ValueError("source secret file permissions must exclude group and others")
            if metadata.st_size > 16 * 1024:
                raise ValueError("source secret file exceeds size budget")
            payload = json.loads(handle.read(16 * 1024 + 1))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise ValueError("source secret file is unreadable or invalid") from error
    if not isinstance(payload, dict):
        raise ValueError("source secret file must contain an object")
    host = payload.get("host")
    user = payload.get("user")
    password = payload.get("password")
    if not isinstance(host, str) or _HOST.fullmatch(host) is None:
        raise ValueError("source host is invalid")
    if not isinstance(user, str) or _USER.fullmatch(user) is None:
        raise ValueError("source user is invalid")
    if not isinstance(password, str) or not password or "\n" in password or "\r" in password:
        raise ValueError("source password cannot use the stdin line protocol")
    if ((configured_host is not None and configured_host != host)
            or (configured_user is not None and configured_user != user)):
        raise ValueError("source host or user does not match secret file")
    return _Credential(host, user, password)


class DockerIbmiSourceDriver:
    """``SourceDriver`` backed by the product's pinned capture image."""

    def __init__(
        self,
        config: RunConfig,
        *,
        runner: Callable[..., Any] = subprocess.run,
        process_factory: Callable[..., Any] = subprocess.Popen,
    ) -> None:
        if config.source.driver != "ibmi_java":
            raise ValueError("source driver must be ibmi_java")
        if _IMAGE_DIGEST.fullmatch(config.capture.image) is None:
            raise ValueError("capture image must be pinned by sha256 digest")
        library, table = config.table.qualified_name.split(".")
        if library.upper() not in {name.upper() for name in config.source.library_whitelist}:
            raise ValueError("source table library is outside the allowlist")
        if any(
            _SOURCE_NAME.fullmatch(value) is None
            for value in (library, table, config.source.journal_library, config.source.journal_name,
                          config.table.primary_key, *config.table.column_names)
        ):
            raise ValueError("source identifier is invalid")
        self.config = config
        self._runner = runner
        self._process_factory = process_factory
        self._warm: Any = None
        self._warm_name: str | None = None
        self._warm_thread: threading.Thread | None = None
        self._warm_lines: queue.Queue[str | None] = queue.Queue(maxsize=8)
        self._warm_index = 0
        self._warm_failed = False
        self._credential = _load_credential(
            config.source.connection_secret_file,
            configured_host=config.source.host, configured_user=config.source.user,
        )
        self._library = library
        self._table = table
        self._allowed_sql: frozenset[str] | None = None

    def execute(self, statements: Sequence[str]) -> SourceResult:
        if not self.config.source.allow_dml:
            return SourceResult(exit_code=5)
        if self._allowed_sql is None:
            generated = {
                statement
                for step in DML_STEP_NAMES
                for statement in step_plan(step, self.config.table).statements
            }
            if "freshness" in self.config.steps:
                generated.update(
                    update_sql(self.config.table, 1, {LABEL: marker})
                    for marker in freshness_markers(self.config.run_id)
                )
            self._allowed_sql = frozenset(generated)
        if not statements or any(statement not in self._allowed_sql for statement in statements):
            raise ValueError("only generated qualification DML is allowed")
        if self._warm is not None:
            return self._execute_warm(statements)
        return self._run("exec", statements)

    def prepare_freshness(self) -> SourceResult:
        """Connexion TLS/JDBC et SELECT 1, sans écriture avant readiness."""
        if (self._warm is not None or not self.config.source.allow_dml
                or "freshness" not in self.config.steps
                or str(UUID(self.config.run_id)) != self.config.run_id):
            raise ValueError("invalid freshness preparation")
        sql = tuple(update_sql(self.config.table, 1, {LABEL: marker})
                    for marker in freshness_markers(self.config.run_id))
        label = self.config.table.column(LABEL)
        if (self.config.table.primary_key != "ORDER_ID" or label.kind != "varchar"
                or label.length is not None and any(len(marker) > label.length
                                                   for marker in freshness_markers(self.config.run_id))):
            raise ValueError("unsupported freshness schema")
        self._warm_failed = False
        self._warm_index = 0
        self._warm_lines = queue.Queue(maxsize=8)
        self._warm_name = f"qdt-qual-source-{uuid4().hex}"
        command = ["docker", "run", "--rm", "--name", self._warm_name,
                   "--interactive", "--pull=never", "--read-only", "--network", "host",
                   "--tmpfs", "/tmp:rw,nosuid,size=16m", "--pids-limit", "128", "--memory", "512m",
                   "--cpus", "1", "--security-opt", "no-new-privileges", "--cap-drop", "ALL",
                   "--entrypoint", "java", self.config.capture.image, "-cp", _JAVA_CLASSPATH,
                   _JAVA_CLASS, "freshness-worker", self._library, self._table,
                   self.config.source.journal_library, self.config.source.journal_name,
                   self.config.table.primary_key, ",".join(self.config.table.column_names), self.config.run_id]
        try:
            self._warm = self._process_factory(command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                              stderr=subprocess.DEVNULL, text=True, bufsize=1)
            process = self._warm
            lines = self._warm_lines
            def pump() -> None:
                try:
                    for line in process.stdout:
                        lines.put(line.rstrip("\n")[:256], timeout=1)
                finally:
                    self._warm_failed = True
                    try:
                        lines.put(None, timeout=1)
                    except queue.Full:
                        pass
            self._warm_thread = threading.Thread(target=pump, daemon=True)
            self._warm_thread.start()
            self._warm.stdin.write("\n".join((self._credential.host, self._credential.user,
                                               self._credential.password, *sql)) + "\n")
            self._warm.stdin.flush()
            ready = self._warm_lines.get(timeout=min(120, self.config.capture.max_seconds))
            if ready != "SRC_FRESHNESS_READY=" + self.config.run_id or self._warm.poll() is not None:
                self._warm_failed = True
                return SourceResult(exit_code=6)
            return SourceResult(exit_code=0, checks=("SRC_CONNECTION_READY=1",))
        except (OSError, queue.Empty):
            self._warm_failed = True
            return SourceResult(exit_code=124)

    def check_freshness(self) -> SourceResult:
        if self._warm is None or self._warm_failed:
            return SourceResult(exit_code=6)
        code = self._warm.poll()
        return SourceResult(exit_code=0 if code is None else (int(code) or 6))

    def _execute_warm(self, statements: Sequence[str]) -> SourceResult:
        index = self._warm_index + 1
        expected = update_sql(self.config.table, 1, {LABEL: freshness_markers(self.config.run_id)[index - 1]}) if index <= 3 else None
        if tuple(statements) != (expected,) or self.check_freshness().exit_code != 0:
            raise ValueError("freshness command outside prepared write budget")
        self._warm_index = index  # Une tentative ambiguë ne peut jamais être rejouée.
        try:
            self._warm.stdin.write(f"FRESHNESS_EXEC={index}\n")
            self._warm.stdin.flush()
            if self._warm_lines.get(timeout=self.config.freshness.max_seconds) != f"SRC_FRESHNESS_ACK={index}":
                self._warm_failed = True
                return SourceResult(exit_code=6)
            return SourceResult(exit_code=0, checks=("SRC_EXEC_TOTAL=1",))
        except (OSError, queue.Empty):
            self._warm_failed = True
            return SourceResult(exit_code=124)

    def close_freshness(self) -> None:
        process, name = self._warm, self._warm_name
        try:
            if process is not None:
                if process.stdin is not None:
                    try:
                        process.stdin.close()
                    except OSError:
                        pass
                if process.poll() is None:
                    process.terminate()
                    try:
                        process.wait(timeout=10)
                    except subprocess.TimeoutExpired:
                        process.kill()
                        process.wait(timeout=5)
                else:
                    process.wait(timeout=5)
        finally:
            try:
                if name is not None:
                    self._cleanup_container(name)
                if self._warm_thread is not None:
                    self._warm_thread.join(timeout=5)
                    if self._warm_thread.is_alive():
                        raise RuntimeError("source output pump did not stop")
            finally:
                self._warm = None
                self._warm_name = None
                self._warm_failed = True

    def tail(self) -> SourceResult:
        return self._run("tail")

    def inspect(self) -> SourceResult:
        """Relit sans mutation le journal attaché à la table configurée."""
        return self._run("inspect")

    def dump(self) -> SourceResult:
        return self._run("dump")

    def row_positions(self, starting: tuple[str, int]) -> SourceResult:
        receiver, sequence = starting
        if _RECEIVER.fullmatch(receiver) is None or isinstance(sequence, bool) or not isinstance(sequence, int) or sequence < 0:
            raise ValueError("source receiver position is invalid")
        return self._run("rowpos", extra=(receiver, str(sequence)))

    def rotate(self) -> SourceResult:
        if not self.config.source.allow_rotation:
            return SourceResult(exit_code=5)
        return self._run("rotate")

    def _cleanup_container(self, name: str) -> None:
        """Arrête uniquement cette invocation et exige son absence réelle."""
        try:
            self._runner(
                ["docker", "rm", "--force", "--volumes", name],
                text=True, capture_output=True, check=False, timeout=15,
            )
            inspected = self._runner(
                ["docker", "container", "inspect", name],
                text=True, capture_output=True, check=False, timeout=15,
            )
            if inspected.returncode != 0 and any(
                marker in (inspected.stderr or "").casefold()
                for marker in ("no such object", "no such container")
            ):
                return
        except (OSError, subprocess.TimeoutExpired):
            pass
        raise RuntimeError("qualification SOURCE container cleanup could not be verified")

    def _run(self, mode: str, statements: Sequence[str] = (), *, extra: tuple[str, ...] = ()) -> SourceResult:
        container_name = f"qdt-qual-source-{uuid4().hex}"
        command = [
            "docker", "run", "--rm", "--name", container_name,
            "--interactive", "--pull=never", "--read-only", "--network", "host",
            "--tmpfs", "/tmp:rw,nosuid,size=16m",
            "--pids-limit", "128", "--memory", "512m", "--cpus", "1",
            "--security-opt", "no-new-privileges", "--cap-drop", "ALL",
            "--entrypoint", "java", self.config.capture.image,
            "-cp", _JAVA_CLASSPATH, _JAVA_CLASS, mode,
            self._library, self._table,
            self.config.source.journal_library, self.config.source.journal_name,
            self.config.table.primary_key, ",".join(self.config.table.column_names),
            *extra,
        ]
        credential = self._credential
        stdin = f"{credential.host}\n{credential.user}\n{credential.password}\n"
        if statements:
            stdin += "".join(statement + "\n" for statement in statements)
        try:
            completed = self._runner(
                command, input=stdin, text=True, capture_output=True,
                timeout=min(120, self.config.capture.max_seconds), check=False,
            )
        except (OSError, subprocess.TimeoutExpired):
            self._cleanup_container(container_name)
            return SourceResult(exit_code=124)
        except BaseException:
            # Une interruption ne doit pas libérer le propriétaire SOURCE
            # tandis que le conteneur peut encore exécuter sa requête.
            self._cleanup_container(container_name)
            raise
        if completed.returncode != 0:
            self._cleanup_container(container_name)
            return SourceResult(exit_code=int(completed.returncode))
        accepted = {
            "exec": ("SRC_EXEC_TOTAL=",),
            "tail": ("SRC_TAIL=", "SRC_TAIL_COUNT="),
            "inspect": ("SRC_JOURNAL=",),
            "dump": ("SRC_ROW=", "SRC_ROW_COUNT="),
            "rowpos": ("SRC_RECEIVER=", "SRC_ROWPOS=", "SRC_ROWPOS_COUNT="),
            "rotate": ("SRC_ROTATION_STARTED=", "SRC_ROTATION_ACK=", "SRC_ROTATED="),
        }[mode]
        checks = tuple(
            line for line in (completed.stdout or "").splitlines()
            if line.startswith(accepted)
        )
        if mode == "exec" and checks != (f"SRC_EXEC_TOTAL={len(statements)}",):
            return SourceResult(exit_code=6)
        if mode == "tail":
            rows = [line for line in checks if line.startswith("SRC_TAIL=")]
            counts = [line for line in checks if line.startswith("SRC_TAIL_COUNT=")]
            if not rows or counts != [f"SRC_TAIL_COUNT={len(rows)}"]:
                return SourceResult(exit_code=6)
        if mode == "inspect" and len(checks) != 1:
            return SourceResult(exit_code=6)
        if mode in {"dump", "rowpos"}:
            prefix = "SRC_ROW" if mode == "dump" else "SRC_ROWPOS"
            counts = [line for line in checks if line.startswith(prefix + "_COUNT=")]
            rows = [line for line in checks if line.startswith(prefix + "=")]
            if (len(counts) != 1 or counts[0] != f"{prefix}_COUNT={len(rows)}"
                    or (mode == "rowpos" and not any(line.startswith("SRC_RECEIVER=") for line in checks))):
                return SourceResult(exit_code=6)
        if mode == "rotate":
            try:
                if len(checks) != 3 or not checks[0].startswith("SRC_ROTATION_STARTED=") or not checks[1].startswith("SRC_ROTATION_ACK=") or checks[2] != "SRC_ROTATED=true":
                    raise ValueError("rotation receipt absent")
                ack = json.loads(checks[1].split("=", 1)[1])
                if (set(ack) != {"started_utc", "ack_utc", "attempts", "acknowledged", "sequence_option", "journal_library", "journal_name"}
                        or ack["journal_library"] != self.config.source.journal_library or ack["journal_name"] != self.config.source.journal_name
                        or ack["started_utc"] != checks[0].split("=", 1)[1]
                        or type(ack["attempts"]) is not int or ack["attempts"] != 1
                        or ack["acknowledged"] is not True or ack["sequence_option"] != "CONT"):
                    raise ValueError("rotation receipt invalid")
                started, acknowledged = (datetime.fromisoformat(ack[k]) for k in ("started_utc", "ack_utc"))
                if started.tzinfo is None or acknowledged.tzinfo is None or not started <= acknowledged:
                    raise ValueError("rotation times invalid")
            except (ValueError, TypeError, KeyError):
                return SourceResult(exit_code=6)
        return SourceResult(exit_code=0, checks=checks)
